import ArgumentParser
import Foundation
import StabilityCore

struct SwiftUIStability: ParsableCommand {
    static let configuration = CommandConfiguration(
        commandName: "swiftui-stability",
        abstract: "Reports which SwiftUI views can skip `body` when their parent re-renders, and why.",
        version: "0.8.0",
        subcommands: [Analyze.self, Dump.self, Check.self, Trace.self],
        defaultSubcommand: Analyze.self
    )
}

struct Sources: ParsableArguments {
    @Argument(help: "Swift files or directories to analyze. Pass a whole module so types resolve across files.")
    var paths: [String] = ["."]

    @Option(name: .customLong("exclude"), help: "Skip paths containing this text (repeatable).")
    var excluded: [String] = []

    func analyze() throws -> [ViewReport] {
        Analyzer.analyze(try SourceFiles.load(paths, excluding: excluded))
    }
}

enum Format: String, ExpressibleByArgument, CaseIterable {
    case text, json, xcode
}

struct Analyze: ParsableCommand {
    static let configuration = CommandConfiguration(abstract: "Show each view's skippability, property stability and findings.")

    @OptionGroup var sources: Sources

    @Option(help: "text, json, or xcode (`file:line: warning:` lines for a build phase or plugin).")
    var format: Format = .text

    @Flag(name: .customLong("json"), help: "Same as --format json.")
    var jsonFlag = false

    @Flag(help: "Only views that can't always skip, and only their non-stable properties.")
    var unstableOnly = false

    @Option(help: "Also write the full JSON report to this file.")
    var report: String?

    @Option(help: .hidden)
    var stamp: String?

    @Option(help: .hidden)
    var trigger: String?

    func run() throws {
        let reports = try sources.analyze()
        if let report {
            try JSON.encode(reports).write(toFile: report, atomically: true, encoding: .utf8)
        }
        if let stamp {
            // The build tool plugin's declared output. A comment-only Swift file compiles to nothing; any
            // other file type would be copied into the target's resource bundle. Rewritten only when it
            // changes, so the compiler has nothing to redo.
            let content = "// Generated by swiftui-stability. \(TextReport.summary(reports))\n"
            if (try? String(contentsOfFile: stamp, encoding: .utf8)) != content {
                try content.write(toFile: stamp, atomically: true, encoding: .utf8)
            }
        }
        if let trigger {
            // Also one of the build command's inputs: touching it after the run keeps the command out of date, so
            // it runs on every build. Build systems don't replay a custom command's warnings, so a skipped run
            // would clear them from Xcode's Issue navigator.
            try Data().write(to: URL(fileURLWithPath: trigger))
        }
        switch jsonFlag ? .json : format {
        case .text: print(TextReport.render(reports, unstableOnly: unstableOnly))
        case .json: print(try JSON.encode(reports))
        case .xcode:
            print(XcodeDiagnostics.render(reports))
            print(XcodeDiagnostics.summary(reports, reportPath: report))
        }
    }
}

struct Dump: ParsableCommand {
    static let configuration = CommandConfiguration(abstract: "Write the stability baseline to commit (like Compose's stabilityDump).")

    @OptionGroup var sources: Sources

    @Option(name: [.short, .long], help: "Baseline file to write.")
    var output = "stability/baseline.stability"

    func run() throws {
        let reports = try sources.analyze()
        let url = URL(fileURLWithPath: output)
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try Baseline(reports: reports).render().write(to: url, atomically: true, encoding: .utf8)
        print("Wrote \(output): \(TextReport.summary(reports))")
    }
}

struct Check: ParsableCommand {
    static let configuration = CommandConfiguration(
        abstract: "Compare against the baseline and fail on changes (like Compose's stabilityCheck).",
        discussion: "Exit status 1 when the check fails. Accept intended changes by running `dump` again and committing the file."
    )

    @OptionGroup var sources: Sources

    @Option(name: [.short, .long], help: "Committed baseline file.")
    var baseline = "stability/baseline.stability"

    @Flag(help: "Fail only on regressions (a view or property getting less stable), not on every change.")
    var ignoreNonRegressive = false

    @Flag(help: "Pass when the baseline file doesn't exist yet.")
    var allowMissingBaseline = false

    @Flag(help: "Print the result as JSON.")
    var json = false

    func run() throws {
        guard FileManager.default.fileExists(atPath: baseline) else {
            if allowMissingBaseline {
                print("No baseline at \(baseline); skipping (run `swiftui-stability dump` to create one).")
                return
            }
            throw ValidationError("No baseline at \(baseline). Run `swiftui-stability dump` and commit it.")
        }
        let committed = try Baseline(parsing: String(contentsOfFile: baseline, encoding: .utf8))
        let changes = committed.changes(to: Baseline(reports: try sources.analyze()))
        let failing = changes.filter { $0.regression || !ignoreNonRegressive }

        if json {
            struct Result: Encodable { var passed: Bool; var changes: [BaselineChange] }
            print(try JSON.encode(Result(passed: failing.isEmpty, changes: changes)))
        } else if changes.isEmpty {
            print("Stability matches \(baseline).")
        } else {
            for change in changes {
                print(change.line + (change.regression ? "   ← regression" : ""))
            }
            print(failing.isEmpty
                  ? "\nNo regressions (\(changes.count) other changes). Run `swiftui-stability dump` to update the baseline."
                  : "\n\(failing.count) failing change(s). If intended, run `swiftui-stability dump` and commit \(baseline).")
        }
        if !failing.isEmpty { throw ExitCode(1) }
    }
}

struct Trace: ParsableCommand {
    static let configuration = CommandConfiguration(
        abstract: "Measure body runs per view with Instruments, and compare them with the static analysis.",
        discussion: """
        Records with the "View Body" instrument (no code changes to the app), then lists each app view's body \
        runs and time, hottest first. With --sources, each view is compared with the analyzer's prediction: \
        confirmed (predicted to re-run, and hot), unexplained (hot, no predicted cause), not-rerunning \
        (predicted, but cold), quiet.

          swiftui-stability trace --app MyApp.app --device <udid> --sources MyApp/
          swiftui-stability trace --attach MyApp --device <udid> --time-limit 20s   # interact meanwhile
          swiftui-stability trace --trace recording.trace --sources MyApp/
        """
    )

    @Option(help: "Launch this .app for the recording (built for the --device).")
    var app: String?

    @Option(help: "Attach to a running app by process name or PID.")
    var attach: String?

    @Option(name: .customLong("trace"), help: "Read an existing .trace instead of recording.")
    var existing: String?

    @Option(help: "Simulator or device (name or UDID) to record on.")
    var device: String?

    @Option(help: "How long to record, e.g. 10s or 1m.")
    var timeLimit = "10s"

    @Option(name: [.short, .long], help: "Keep the recording at this path (default: a temporary file).")
    var output: String?

    @Option(name: .customLong("sources"), help: "Analyze these sources and compare (repeatable).")
    var sources: [String] = []

    @Option(help: "Body runs that make a view hot.")
    var hot = 10

    @Flag(help: "Print JSON.")
    var json = false

    func validate() throws {
        let given = [app, attach, existing].compactMap { $0 }.count
        guard given == 1 else { throw ValidationError("Pass exactly one of --app, --attach or --trace.") }
    }

    func run() throws {
        let tracePath: String
        if let existing {
            tracePath = existing
        } else {
            tracePath = output ?? FileManager.default.temporaryDirectory
                .appending(path: "swiftui-stability-\(UUID().uuidString).trace").path()
            let target: Xctrace.Target = if let app { .launch(app: app) } else { .attach(attach!) }
            if !json { print("Recording \(timeLimit) with the \(BodyTrace.instrument) instrument…") }
            try Xctrace.record(target, device: device, timeLimit: timeLimit, output: tracePath)
        }
        let trace = try Xctrace.bodyTrace(from: tracePath)
        let reports = sources.isEmpty ? [] : Analyzer.analyze(try SourceFiles.load(sources))
        let check = RealityCheck(trace: trace, reports: reports, hotThreshold: hot)

        if json {
            struct Result: Encodable { var trace: String; var duration: Double?; var rows: [RealityCheck.Row] }
            print(try JSON.encode(Result(trace: tracePath, duration: trace.duration, rows: check.rows)))
        } else {
            print(check.render(duration: trace.duration))
            if sources.isEmpty { print("Pass --sources <dir> to compare with the static analysis.") }
            print("Trace: \(tracePath)")
        }
    }
}

SwiftUIStability.main()
